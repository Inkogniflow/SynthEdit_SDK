# Generates stub implementations (all pure virtuals return {}) for SDK interfaces.
import re, sys
import os
SDK=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','se_sdk3')+'/'
def strip_comments(s):
    s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
    return re.sub(r'//[^\n]*','',s)
classes={}
for hdr in ['mp_api.h','mp_sdk_gui2.h','Drawing_API.h']:
    text=strip_comments(open(SDK+hdr,encoding='latin-1').read())
    # track namespace by position
    for m in re.finditer(r'class\s+(?:DECLSPEC_NOVTABLE\s+)?(\w+)\s*:\s*public\s+([\w:]+)\s*\{',text):
        name,base=m.group(1),m.group(2)
        # find body end by brace matching
        i=m.end(); depth=1
        while depth: 
            c=text[i]; depth+= (c=='{')-(c=='}'); i+=1
        body=text[m.end():i-1]
        ns=None
        for nm in re.finditer(r'namespace\s+(\w+)\s*\{',text[:m.start()]): ns=nm.group(1)
        methods=[(r.strip(),n,p.strip()) for r,n,p in re.findall(r'virtual\s+([\w:\*&\s]+?)\s+MP_STDCALL\s+(\w+)\s*\(([^)]*)\)\s*(?:const\s*)?=\s*0\s*;',body)]
        classes.setdefault(f'{ns}::{name}', dict(base=base, ns=ns, name=name, methods=methods))
def lookup(base, ns):
    if '::' in base: return classes.get(base)
    return classes.get(f'{ns}::{base}') or next((v for k,v in classes.items() if k.endswith('::'+base)), None)
def allmethods(q):
    out=[]; c=classes.get(q)
    while c and c['name']!='IMpUnknown':
        out=c['methods']+out; c=lookup(c['base'], c['ns'])
    seen=set(); res=[]
    for r,n,p in out:
        key=(n,re.sub(r'\s+','',p))
        if key in seen: continue
        seen.add(key); res.append((r,n,p))
    return res
want=sys.argv[1:]
print('#pragma once\n// generated by genstubs.py\n#include "stub_base.h"')
for w in want:
    c=classes[w]; ns=c['ns']; w0=c['name']
    print(f'namespace {ns} {{\nstruct Stub_{w0} : public {w0}, public StubRef {{')
    print('\tSTUB_UNKNOWN_IMPL')
    for r,n,p in allmethods(w):
        ret='{}' if r!='void' else ''
        body='' if r=='void' else ' return {};'
        print(f'\t{r} MP_STDCALL {n}({p}) override {{ log_call("{w0}::{n}");{body} }}')
    print('};\n}')
